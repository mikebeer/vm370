  if ((Get-Item $f).Length -ne $e[1]) { throw "size mismatch: $f" }
}
# pack into parts of at most ~24 MB
$parts = @(); $cur = @(); $sz = 0
foreach ($f in (Get-ChildItem $out -Filter *.deb | Sort-Object Name)) {
  if ($sz + $f.Length -gt 24MB -and $cur.Count -gt 0) { $parts += ,$cur; $cur = @(); $sz = 0 }
  $cur += $f.FullName; $sz += $f.Length
}
if ($cur.Count -gt 0) { $parts += ,$cur }
$n = 0
foreach ($p in $parts) {
  $n++; $z = "wheezy-s390-part$n.zip"
  if (Test-Path $z) { Remove-Item $z }
  Compress-Archive -Path $p -DestinationPath $z -CompressionLevel Optimal
  Write-Host "$z  ($($p.Count) packages)"
}
Write-Host "Done: upload the wheezy-s390-part*.zip files."
